#!/usr/bin/env node
/** Verify the exact, generated resource-only Tauri override before packaging. */
import {lstatSync, readFileSync} from 'node:fs';
import {basename, dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const APPROVED_PLACES_OVERRIDE = Object.freeze({
  bundle: Object.freeze({
    active: true,
    resources: Object.freeze({
      '../.local/places/world-cities.sqlite': 'places/world-cities.sqlite',
      '../.local/places/world-cities.manifest.json': 'places/world-cities.manifest.json',
    }),
  }),
});
const CANONICAL = JSON.stringify(APPROVED_PLACES_OVERRIDE, null, 2) + '\n';

function requireOrdinaryDirectory(path) {
  let stat;
  try { stat = lstatSync(path); } catch {
    throw new Error('Unapproved Tauri city override directory');
  }
  if (!stat.isDirectory() || stat.isSymbolicLink()) {
    throw new Error('Unapproved Tauri city override directory');
  }
}

export function verifyPlacesTauriOverride(path=join(ROOT, '.local/places/tauri-places.conf.json')) {
  // Match the local pack layout used by the Python producer. The verifier
  // must not follow a linked .local or places directory outside this checkout.
  const override = resolve(path);
  const placesDir = dirname(override);
  const localDir = dirname(placesDir);
  if (basename(override) !== 'tauri-places.conf.json' ||
      basename(placesDir) !== 'places' || basename(localDir) !== '.local') {
    throw new Error('Unapproved Tauri city override location');
  }
  requireOrdinaryDirectory(localDir);
  requireOrdinaryDirectory(placesDir);
  // The override is generated by prepare_tauri_bundle.py, not hand-authored.
  // Exact canonical text also rejects duplicate JSON keys, which JSON.parse
  // would silently accept. Python text writes may use CRLF on Windows.
  let stat;
  try { stat = lstatSync(override); } catch {
    throw new Error('Unapproved Tauri city override file');
  }
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 4096) {
    throw new Error('Unapproved Tauri city override file');
  }
  let source;
  try { source = readFileSync(override, 'utf8').replace(/\r\n/g, '\n'); }
  catch { throw new Error('Unapproved Tauri city override file'); }
  if (source !== CANONICAL) {
    throw new Error('Tauri city override differs from generated resource-only template');
  }
  return Object.freeze({approvedResources:2});
}

if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length!==2) throw new Error('No CLI options allowed');
    const result=verifyPlacesTauriOverride();
    console.log('Verified '+result.approvedResources+' local city resources in Tauri override.');
  } catch {
    // No local file paths, manifest data or contents in CI/build output.
    console.error('TAURI CITY OVERRIDE VERIFICATION FAILED: regenerate the local resource-only configuration.');
    process.exitCode=1;
  }
}
